import {
  ACTION_COMMAND_TYPE,
  NATIVE_COMMAND_TYPE,
  SCHEDULED_ACTION_COMMAND_TYPE
} from "./command-common.js";

function cell(value) {
  return String(value ?? "—")
    .replaceAll("|", "\\|")
    .replaceAll("\n", " ");
}

function table(headers, rows) {
  if (rows.length === 0) return "_None._\n";
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
    ""
  ].join("\n");
}

function commandOwners(registry) {
  const owners = new Map();
  for (const feature of registry.features) {
    for (const platform of ["discord", "twitch"]) {
      for (const command of feature.commands[platform]) owners.set(command, feature.id);
    }
  }
  return owners;
}

function routeOwners(registry) {
  const owners = new Map();
  for (const feature of registry.features) {
    for (const route of feature.routes) owners.set(route, feature.id);
  }
  return owners;
}

function triggerOwners(registry, collection) {
  const owners = new Map();
  for (const feature of registry.features) {
    for (const definition of feature[collection]) owners.set(definition, feature.id);
  }
  return owners;
}

function valueList(values) {
  const rendered = values.map((value) => `\`${String(value)}\``);
  if (rendered.length === 1) return rendered[0];
  if (rendered.length === 2) return rendered.join(" or ");
  return `${rendered.slice(0, -1).join(", ")}, or ${rendered.at(-1)}`;
}

function actionAccess(action) {
  if (!action) return "public";
  const baseline = action.capability ?? "public";
  const conditional = action.conditionalAccess.map(({ capability, when }) =>
    `${capability} when \`${when.argument}\` is ${valueList(when.values)}`
  );
  return [baseline, ...conditional].join("; ");
}

function commandAccess(registry, command) {
  if (command.mode === ACTION_COMMAND_TYPE) {
    return actionAccess(registry.actions[command.actionKind]);
  }
  if (command.mode === SCHEDULED_ACTION_COMMAND_TYPE) {
    const schedule = registry.schedules[command.scheduleKind];
    return actionAccess(registry.actions[schedule?.actionKind]);
  }
  return command.capability ?? "public";
}

function commandType(mode) {
  if (mode === ACTION_COMMAND_TYPE) return "action";
  if (mode === SCHEDULED_ACTION_COMMAND_TYPE) return "scheduled action";
  if (mode === NATIVE_COMMAND_TYPE) return "native";
  return mode;
}

export function generateFeatureCatalogMarkdown(
  registry,
  { workspacePackages = [] } = {}
) {
  const commandOwner = commandOwners(registry);
  const routeOwner = routeOwners(registry);
  const eventOwner = triggerOwners(registry, "events");
  const scheduleOwner = triggerOwners(registry, "schedules");
  const packageByFeatureId = new Map(
    workspacePackages.map((workspacePackage) => [
      workspacePackage.featureId,
      workspacePackage.packageName
    ])
  );
  const featureRows = registry.features.map((feature) => [
    `\`${feature.id}\``,
    packageByFeatureId.has(feature.id)
      ? `\`${packageByFeatureId.get(feature.id)}\``
      : "repository-local",
    feature.description,
    feature.actions.length,
    feature.commands.discord.length,
    feature.commands.twitch.length
  ]);
  const workspaceRows = workspacePackages.map((workspacePackage) => [
    `\`${workspacePackage.packageName}\``,
    `\`${workspacePackage.featureId}\``,
    workspacePackage.installed ? "yes" : "no"
  ]);
  const commandRows = ["discord", "twitch"].flatMap((platform) =>
    Object.values(registry.commands[platform]).map((command) => [
      commandOwner.get(command),
      platform === "discord" ? `\`/${command.name}\`` : `\`!${command.name}\``,
      commandType(command.mode),
      commandAccess(registry, command),
      command.description
    ])
  );
  const actionRows = Object.values(registry.actions).map((action) => [
    action.featureId,
    `\`${action.kind}\``,
    action.supportedOrigins.join(", "),
    actionAccess(action),
    action.uses.services.join(", ") || "—",
    action.cooldown ? `${action.cooldown.scope}, ${action.cooldown.seconds}s` : "—"
  ]);
  const routeRows = Object.values(registry.routes).map((route) => [
    routeOwner.get(route),
    `\`${route.kind}\``,
    route.sourcePlatform,
    route.targetPlatform,
    route.destination,
    route.newIntegration,
    route.existingIntegration
  ]);
  const eventRows = Object.values(registry.events).map((event) => [
    eventOwner.get(event),
    `\`${event.eventKind}\``,
    `\`${event.actionKind}\``
  ]);
  const scheduleRows = Object.values(registry.schedules).map((schedule) => [
    scheduleOwner.get(schedule),
    `\`${schedule.kind}\``,
    `\`${schedule.actionKind}\``,
    schedule.timing,
    schedule.authorization
  ]);

  return [
    "# Installed feature catalog",
    "",
    "<!-- Generated by `npm run feature:docs`. Do not edit by hand. -->",
    "",
    "This catalog is generated from the installed feature registry. It covers",
    "contributor-framework features; legacy commands remain documented in the README.",
    `Framework API: v${registry.apiVersion}.`,
    "",
    "## Features",
    "",
    table(
      [
        "Feature",
        "Source",
        "Description",
        "Actions",
        "Discord commands",
        "Twitch commands"
      ],
      featureRows
    ),
    "## Workspace packages",
    "",
    table(["Package", "Feature", "Installed by Worker"], workspaceRows),
    "## Commands",
    "",
    table(["Feature", "Command", "Type", "Access", "Description"], commandRows),
    "## Actions",
    "",
    table(
      ["Feature", "Action kind", "Origins", "Access", "Services", "Cooldown"],
      actionRows
    ),
    "## Routes",
    "",
    table(
      [
        "Feature",
        "Route kind",
        "Source",
        "Target",
        "Destination",
        "New links",
        "Existing links"
      ],
      routeRows
    ),
    "## Events",
    "",
    table(["Feature", "Event kind", "Action kind"], eventRows),
    "## Schedules",
    "",
    table(
      ["Feature", "Schedule kind", "Action kind", "Timing", "Authorization"],
      scheduleRows
    )
  ].join("\n");
}
